#!/usr/bin/env node
// Builds js/lecture-library-auto.js from scripts/lectures/found.json (YouTube playlists and videos
// found by search, one entry per subject). Every topic gets a link: the best-matching video found
// for its unit, else the unit's main video, else a whole-course video, else the subject playlist.
//   node scripts/lectures/build_from_found.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadSiteData, tokens } from './fetch_youtube_lectures.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const FOUND = path.join(ROOT, 'scripts/lectures/found.json');
const OUT = path.join(ROOT, 'js/lecture-library-auto.js');
const REPORT = path.join(ROOT, 'scripts/lectures/REPORT.md');

function score(topic, video) {
  const q = [...new Set(tokens(topic))];
  if (!q.length) return 0;
  const v = new Set(tokens(video.t));
  return q.filter((t) => v.has(t)).length / q.length;
}

export function buildCourse(course, found) {
  const base = { semester: course.semester, subject: course.id, subjectCode: course.code, subjectLabel: course.title };
  const pl = found.playlist;
  const videos = found.videos || [];
  const entries = [];
  if (pl) {
    entries.push({
      ...base,
      title: `${course.title}: full lecture series`,
      lecturer: pl.by,
      type: 'playlist',
      typeLabel: 'Full course playlist',
      topics: course.units.map((u) => u.title),
      description: `"${pl.title}" by ${pl.by}.`,
      url: `https://www.youtube.com/playlist?list=${pl.id}`,
      lectureKey: `${course.id}-auto-playlist`,
    });
  }
  const stats = { topics: 0, topic: 0, unit: 0, course: 0, playlist: 0 };
  for (const unit of course.units) {
    const unitVids = videos.filter((v) => v.u === unit.unitNumber);
    const courseVids = videos.filter((v) => v.u === 0);
    for (const [i, topic] of unit.topics.entries()) {
      stats.topics += 1;
      let pick = null;
      let kind = null;
      let best = 0;
      for (const v of [...unitVids, ...courseVids]) {
        const s = score(topic.title, v);
        if (s > best) { best = s; pick = v; }
      }
      if (pick && best >= 0.34) kind = 'topic';
      else if (unitVids.length) { pick = unitVids[0]; kind = 'unit'; }
      else if (courseVids.length) { pick = courseVids[0]; kind = 'course'; }
      else if (pl) { pick = null; kind = 'playlist'; }
      else continue;
      stats[kind] += 1;
      entries.push({
        ...base,
        title: topic.title,
        unit: unit.unitNumber,
        topicId: topic.id,
        lecturer: pick ? pick.by : pl.by,
        type: pick && !pick.id.startsWith("PL") ? "video" : "playlist",
        typeLabel: `Unit ${unit.unitNumber}: ${unit.title}`,
        topics: [topic.title],
        description: pick
          ? (kind === 'topic' ? `"${pick.t}".` : `"${pick.t}" covers ${unit.title}.`)
          : `Full ${course.title} series; pick the lecture on ${unit.title}.`,
        url: pick ? (pick.id.startsWith("PL") ? `https://www.youtube.com/playlist?list=${pick.id}` : `https://www.youtube.com/watch?v=${pick.id}`) : `https://www.youtube.com/playlist?list=${pl.id}`,
        lectureKey: `${course.id}-u${unit.unitNumber}-t${i + 1}`,
        match: kind,
      });
    }
  }
  return { entries, stats };
}

function main() {
  const { courses, curated } = loadSiteData(ROOT);
  const curatedIds = new Set(curated.map((c) => c.subject));
  const found = JSON.parse(fs.readFileSync(FOUND, 'utf8'));
  const all = [];
  const rows = [];
  const tot = { subjects: 0, covered: 0, topics: 0, topic: 0, unit: 0, course: 0, playlist: 0 };
  for (const c of courses) {
    if (curatedIds.has(c.id)) continue;
    tot.subjects += 1;
    const t = c.units.reduce((n, u) => n + u.topics.length, 0);
    tot.topics += t;
    const f = found[c.id];
    if (!f) { rows.push(`| ${c.code} | ${c.title} | ${c.semester} | none yet | ${t} | 0 |`); continue; }
    const { entries, stats } = buildCourse(c, f);
    all.push(...entries);
    tot.covered += 1;
    for (const k of ['topic', 'unit', 'course', 'playlist']) tot[k] += stats[k];
    const linked = stats.topic + stats.unit + stats.course + stats.playlist;
    rows.push(`| ${c.code} | ${c.title} | ${c.semester} | ${f.playlist ? `[${f.playlist.by}](https://www.youtube.com/playlist?list=${f.playlist.id})` : '-'} | ${t} | ${linked} (${stats.topic + stats.unit} with own video) |`);
  }
  fs.writeFileSync(OUT, '// Generated by scripts/lectures/build_from_found.mjs from scripts/lectures/found.json. Do not edit by hand.\n'
    + '// YouTube lectures for subjects without a hand-curated shelf (js/lecture-library.js).\n'
    + `window.lectureLibraryAuto = ${JSON.stringify(all, null, 1)};\n`);
  const md = `# Lecture coverage\n\nBuilt by \`scripts/lectures/build_from_found.mjs\` from \`found.json\`.\n\n`
    + `- Subjects with lectures: **${tot.covered} / ${tot.subjects}**\n`
    + `- Topics linked: **${tot.topic + tot.unit + tot.course + tot.playlist} / ${tot.topics}**\n`
    + `  - matched to a video about the topic: ${tot.topic}\n  - unit lecture video: ${tot.unit}\n`
    + `  - whole-course video: ${tot.course}\n  - subject playlist only: ${tot.playlist}\n\n`
    + 'Report a broken link by subject code and topic; it gets replaced in `found.json`.\n\n'
    + '| Code | Subject | Sem | Playlist | Topics | Linked |\n|---|---|---|---|---|---|\n' + rows.join('\n') + '\n';
  fs.writeFileSync(REPORT, md);
  console.log(md.split('\n').slice(0, 10).join('\n'));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
