#!/usr/bin/env node
/**
 * Academy LMS - study resource builder for the multi-branch curriculum.
 *
 * For every subject in scripts/curriculum/*.txt it writes into assets/resources/<id>/:
 *   notes/<id>-unit-wise-study-notes.{md,pdf}          unit-wise revision handbook
 *   mock-papers/<id>-rgpv-model-question-paper.{md,pdf} RGPV-pattern model paper (8 questions, attempt any 5)
 *   mock-papers/<id>-question-bank-with-answers.md       unit-wise short/long questions with answer hints
 * and registers them in js/resource-library.js (generated block, existing entries untouched).
 *
 * Model papers are practice papers generated from the syllabus, not past RGPV papers.
 * Run after build_multibranch_curriculum.js:  node scripts/build_study_resources.js
 */
const fs = require('fs');
const path = require('path');
const PDFDocument = require('pdfkit');
const { parseSources, resourcePaths, REFERENCES } = require('./build_multibranch_curriculum.js');
const { BRANCHES, PLAN } = require('./curriculum/plan.js');

const ROOT = path.join(__dirname, '..');
const FONT = path.join(__dirname, 'fonts', 'DejaVuSans.ttf');
const FONT_BOLD = path.join(__dirname, 'fonts', 'DejaVuSans-Bold.ttf');
const LIB_FILE = path.join(ROOT, 'js', 'resource-library.js');
const START = '// <<MULTIBRANCH-RESOURCES:START>> (generated by scripts/build_study_resources.js)';
const END = '// <<MULTIBRANCH-RESOURCES:END>>';

// where each course appears: [{branch, sem, code}]
function placements() {
    const map = {};
    Object.entries(PLAN).forEach(([branch, sems]) => {
        Object.entries(sems).forEach(([sem, list]) => {
            list.forEach(({ id, code }) => {
                (map[id] = map[id] || []).push({ branch, sem: Number(sem), code });
            });
        });
    });
    return map;
}

function rotate(list, n) {
    if (!list.length) return list;
    const k = n % list.length;
    return [...list.slice(k), ...list.slice(0, k)];
}

// ---------------------------------------------------------------- content
function notesSections(course) {
    return course.units.map((unit, ui) => ({
        heading: `Unit ${ui + 1}: ${unit.title}`,
        topics: unit.topics.map((t) => ({ title: t.title, overview: t.overview, terms: t.terms }))
    }));
}

function modelPaper(course, set) {
    // 8 questions; Q1-Q5 map to units 1-5, Q6-Q8 mix units. Each has (a) short-answer 7 marks, (b) long 7 marks.
    const units = course.units;
    const qs = [];
    for (let q = 0; q < 8; q += 1) {
        const u = q < 5 ? q : (q * 2 + set) % units.length;
        const unit = units[u];
        const topics = rotate(unit.topics, set + q + (q >= 5 ? 2 : 0));
        const a = topics[0];
        const b = topics[1] || topics[0];
        const ta = a.terms[(set + q) % a.terms.length];
        const tb = b.terms.slice(0, 2).map((t) => t.term);
        qs.push({
            unit: u + 1,
            a: `Define ${ta.term}. Explain its role in ${a.title} with a suitable example or diagram.`,
            aHint: `${ta.term}: ${ta.def}`,
            b: q % 2 === set % 2
                ? `Explain ${b.title} in detail. Differentiate between ${tb.join(' and ')}.`
                : `With a neat sketch, discuss ${b.title}. Bring out the significance of ${tb.join(' and ')}.`,
            bHint: b.terms.map((t) => `${t.term}: ${t.def}`).join(' | ')
        });
    }
    return qs;
}

function paperMarkdown(course, placementsForCourse) {
    const codes = placementsForCourse.map((p) => `${BRANCHES[p.branch].short} Sem ${p.sem}: ${p.code}`).join(' · ');
    const sets = [0, 1].map((set) => modelPaper(course, set));
    const lines = [
        `# ${course.code} ${course.title} — RGPV Model Question Paper`,
        '',
        `> Practice paper generated from the RGPV syllabus by Academy LMS. Not an official RGPV paper. Applies to: ${codes}.`,
        '',
        '**Time: 3 Hours | Maximum Marks: 70**',
        '',
        '*Note: Attempt any five questions. All questions carry equal marks. Draw neat diagrams wherever necessary.*',
        ''
    ];
    sets.forEach((qs, si) => {
        lines.push(`## Set ${si === 0 ? 'A' : 'B'}`, '');
        qs.forEach((q, i) => {
            lines.push(`**Q${i + 1}.** *(Unit ${q.unit})*`, '', `(a) ${q.a} **[7]**`, '', `(b) ${q.b} **[7]**`, '');
        });
    });
    lines.push('## Answer Hints (Set A)', '');
    sets[0].forEach((q, i) => {
        lines.push(`- **Q${i + 1}(a):** ${q.aHint}`, `- **Q${i + 1}(b):** ${q.bHint}`);
    });
    lines.push('', '## Recommended Books', '');
    (REFERENCES[course.id] || []).forEach(([t, a]) => lines.push(`- *${t}* — ${a}`));
    return { md: lines.join('\n') + '\n', sets };
}

function notesMarkdown(course) {
    const lines = [
        `# ${course.code} ${course.title} — Unit-wise Study Notes`,
        '',
        `> ${course.description}`,
        ''
    ];
    notesSections(course).forEach((sec) => {
        lines.push(`## ${sec.heading}`, '');
        sec.topics.forEach((t) => {
            lines.push(`### ${t.title}`, '', t.overview, '');
            t.terms.forEach((term) => lines.push(`- **${term.term}:** ${term.def}`));
            lines.push('');
        });
    });
    lines.push('## Standard Textbooks', '');
    (REFERENCES[course.id] || []).forEach(([t, a]) => lines.push(`- *${t}* — ${a}`));
    lines.push('', 'Official syllabus: https://www.rgpv.ac.in (Scheme & Syllabus section).');
    return lines.join('\n') + '\n';
}

function bankMarkdown(course) {
    const lines = [`# ${course.code} ${course.title} — Question Bank with Answer Hints`, ''];
    course.units.forEach((unit, ui) => {
        lines.push(`## Unit ${ui + 1}: ${unit.title}`, '', '### Short answer (2-3 marks)', '');
        unit.topics.forEach((t) => t.terms.forEach((term) => {
            lines.push(`- **Q.** Define *${term.term}*.  `, `  **Ans.** ${term.def}`);
        }));
        lines.push('', '### Long answer (7 marks)', '');
        unit.topics.forEach((t) => {
            lines.push(`- **Q.** Explain *${t.title}* in detail with a neat diagram.  `,
                `  **Key points:** ${t.overview} ${t.terms.map((x) => `${x.term} — ${x.def}`).join('; ')}.`);
        });
        lines.push('');
    });
    return lines.join('\n') + '\n';
}

// ---------------------------------------------------------------- pdf
function newDoc(file) {
    const doc = new PDFDocument({ size: 'A4', margin: 50, bufferPages: true, info: { Author: 'Academy LMS', Producer: 'Academy LMS', CreationDate: new Date('2026-11-16T00:00:00Z') } });
    doc.registerFont('body', FONT);
    doc.registerFont('bold', FONT_BOLD);
    const stream = fs.createWriteStream(file);
    doc.pipe(stream);
    return { doc, done: new Promise((resolve) => stream.on('finish', resolve)) };
}

function header(doc, title, subtitle) {
    doc.rect(0, 0, doc.page.width, 90).fill('#0f172a');
    doc.fillColor('#ffffff').font('bold').fontSize(17).text(title, 50, 26, { width: doc.page.width - 100 });
    doc.fillColor('#94a3b8').font('body').fontSize(9).text(subtitle, 50, doc.y + 4, { width: doc.page.width - 100 });
    doc.fillColor('#111827');
    doc.y = 110;
}

function footer(doc, label) {
    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i += 1) {
        doc.switchToPage(i);
        const bottom = doc.page.margins.bottom;
        doc.page.margins.bottom = 0;
        doc.font('body').fontSize(8).fillColor('#6b7280')
            .text(`${label}  ·  Academy LMS  ·  Page ${i + 1} of ${range.count}`, 50, doc.page.height - 35, { width: doc.page.width - 100, align: 'center' });
        doc.page.margins.bottom = bottom;
    }
}

async function notesPdf(course, file) {
    const { doc, done } = newDoc(file);
    header(doc, `${course.code}  ${course.title}`, `Unit-wise Study Notes  ·  ${course.description}`);
    notesSections(course).forEach((sec, i) => {
        if (i > 0 && doc.y > doc.page.height - 200) doc.addPage();
        doc.moveDown(0.6).font('bold').fontSize(13).fillColor('#1d4ed8').text(sec.heading);
        doc.moveTo(50, doc.y + 2).lineTo(doc.page.width - 50, doc.y + 2).strokeColor('#bfdbfe').stroke();
        doc.moveDown(0.4);
        sec.topics.forEach((t) => {
            doc.font('bold').fontSize(10.5).fillColor('#111827').text(t.title);
            doc.font('body').fontSize(9.5).fillColor('#374151').text(t.overview, { align: 'justify' });
            t.terms.forEach((term) => {
                doc.font('bold').fontSize(9.5).fillColor('#0f766e').text(`• ${term.term}: `, { continued: true, indent: 8 })
                    .font('body').fillColor('#374151').text(term.def);
            });
            doc.moveDown(0.5);
        });
    });
    doc.moveDown(0.8).font('bold').fontSize(12).fillColor('#1d4ed8').text('Standard Textbooks');
    (REFERENCES[course.id] || []).forEach(([t, a]) => doc.font('body').fontSize(9.5).fillColor('#374151').text(`• ${t} — ${a}`));
    doc.moveDown(0.3).fontSize(8.5).fillColor('#6b7280').text('Official syllabus: https://www.rgpv.ac.in (Scheme & Syllabus).');
    footer(doc, `${course.code} Study Notes`);
    doc.end();
    await done;
}

async function paperPdf(course, sets, codes, file) {
    const { doc, done } = newDoc(file);
    header(doc, `${course.code}  ${course.title}`, `RGPV-pattern Model Question Paper  ·  ${codes}`);
    sets.forEach((qs, si) => {
        if (si > 0) doc.addPage();
        doc.font('bold').fontSize(12).fillColor('#111827').text(`Set ${si === 0 ? 'A' : 'B'}`, { align: 'center' });
        doc.font('body').fontSize(9.5).text('Time: 3 Hours                                                                Maximum Marks: 70', { align: 'center' });
        doc.fontSize(8.5).fillColor('#4b5563').text('Note: Attempt any five questions. All questions carry equal marks. Draw neat diagrams wherever necessary.', { align: 'center' });
        doc.moveDown(0.8);
        qs.forEach((q, i) => {
            doc.font('bold').fontSize(10).fillColor('#111827').text(`Q${i + 1}.`, { continued: true }).font('body').fillColor('#6b7280').text(`   (Unit ${q.unit})`);
            doc.font('body').fontSize(10).fillColor('#111827').text(`(a) ${q.a}`, { indent: 14 }).text('[7]', { align: 'right' });
            doc.text(`(b) ${q.b}`, { indent: 14 }).text('[7]', { align: 'right' });
            doc.moveDown(0.4);
        });
    });
    doc.addPage();
    doc.font('bold').fontSize(12).fillColor('#1d4ed8').text('Answer Hints — Set A');
    doc.moveDown(0.3);
    sets[0].forEach((q, i) => {
        doc.font('bold').fontSize(9.5).fillColor('#111827').text(`Q${i + 1}(a)`).font('body').fillColor('#374151').text(q.aHint);
        doc.font('bold').fillColor('#111827').text(`Q${i + 1}(b)`).font('body').fillColor('#374151').text(q.bHint.split(' | ').join('\n'));
        doc.moveDown(0.3);
    });
    doc.moveDown(0.5).fontSize(8).fillColor('#6b7280').text('Practice paper generated from the RGPV syllabus by Academy LMS. It is not an official RGPV question paper.');
    footer(doc, `${course.code} Model Paper`);
    doc.end();
    await done;
}

// ---------------------------------------------------------------- main
async function main() {
    const courses = parseSources();
    const place = placements();
    const entries = [];
    for (const course of courses) {
        const p = resourcePaths(course.id);
        const abs = (rel) => path.join(ROOT, rel);
        [p.notesPdf, p.paperPdf].forEach((rel) => fs.mkdirSync(path.dirname(abs(rel)), { recursive: true }));
        const pl = place[course.id] || [];
        const codes = pl.map((x) => `${BRANCHES[x.branch].short} S${x.sem} ${x.code}`).join(', ');
        const { md: paperMd, sets } = paperMarkdown(course, pl);
        fs.writeFileSync(abs(p.notesMd), notesMarkdown(course));
        fs.writeFileSync(abs(p.paperMd), paperMd);
        fs.writeFileSync(abs(p.bankMd), bankMarkdown(course));
        await notesPdf(course, abs(p.notesPdf));
        await paperPdf(course, sets, codes, abs(p.paperPdf));

        const branches = [...new Set(pl.map((x) => x.branch))];
        const semesters = [...new Set(pl.map((x) => x.sem))];
        const label = course.code.replace(/\s+/g, '');
        const mk = (rel, type, typeLabel, title) => ({
            subject: course.id,
            subjectLabel: label,
            type,
            typeLabel,
            title,
            path: `../${rel}`,
            extension: rel.split('.').pop(),
            branches,
            semesters,
            generated: true
        });
        entries.push(
            mk(p.notesPdf, 'notes', 'Notes', `${course.code} ${course.title} — Unit-wise Study Notes`),
            mk(p.paperPdf, 'mock-papers', 'Mock Papers', `${course.code} ${course.title} — RGPV Model Question Paper`),
            mk(p.bankMd, 'mock-papers', 'Mock Papers', `${course.code} ${course.title} — Question Bank with Answers`)
        );
    }

    const src = fs.readFileSync(LIB_FILE, 'utf8');
    const base = src.includes(START) ? src.slice(0, src.indexOf(START)).trimEnd() : src.trimEnd();
    const block = `${START}
window.resourceLibrary.push(...${JSON.stringify(entries, null, 4)});
${END}
`;
    fs.writeFileSync(LIB_FILE, `${base}\n\n${block}`);
    console.log(`Generated study resources for ${courses.length} subjects (${entries.length} library entries).`);
}

main().catch((err) => {
    console.error(err);
    process.exit(1);
});
